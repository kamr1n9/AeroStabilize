% SATURATION: LQR
% ============================================================

function pct = saturation_percentage_lqr( ...
    t,X,K, ...
    x_des,y_des,z_des, ...
    m_nominal,g,L,k_yaw,Tmin,Tmax)

N = length(t);

sat = false(N,1);

M = [ ...
    1,1,1,1;
    0,L,0,-L;
    -L,0,L,0;
    k_yaw,-k_yaw,k_yaw,-k_yaw];

x_ref = zeros(12,1);

x_ref(1) = x_des;
x_ref(2) = y_des;
x_ref(3) = z_des;

for k = 1:N

    state = X(k,:)';

    u_cmd = [ ...
        m_nominal*g;
        0;
        0;
        0] - ...
        K*(state-x_ref);

    requested = M\u_cmd;

    sat(k) = any( ...
        requested<Tmin | ...
        requested>Tmax);

end

duration = trapz( ...
    t, ...
    double(sat));

pct = ...
    100*duration/(t(end)-t(1));

end

