%% AeroStabilize
% Monte-Carlo Robustness Analysis
%
% Controllers:
%   1) Cascaded PD + Feedforward
%   2) LQR + Feedforward
%   3) LQI + Feedforward
%
% Random uncertainty:
%   - Mass: +/-20%
%   - Inertia: +/-15%
%   - Wind magnitude: 0...5 N
%   - Random horizontal wind direction
%
% Output:
%   - Statistical robustness metrics
%   - RMSE distribution boxplot
%   - Summary bar chart
%
% NOTE:
% The exact same randomized plant/disturbance conditions are
% applied to all three controllers in every Monte-Carlo run.

clear;
clc;
close all;

rng(42);   % Reproducible Monte-Carlo experiment

%% ============================================================
% MONTE-CARLO SETTINGS
% ============================================================

N_runs = 100;

t_start = 0;
t_end   = 20;

%% Desired fixed position

x_des = 1.0;
y_des = 1.0;
z_des = 2.0;

%% Constant disturbance starts here

wind_start = 5.0;

%% Success criterion

success_error_threshold = 0.50;   % final 3D error [m]

%% ============================================================
% NOMINAL PARAMETERS
% ============================================================

g = 9.81;

m_nominal = 1.5;

L = 0.225;

Ix_nominal = 0.020;
Iy_nominal = 0.020;
Iz_nominal = 0.040;

k_yaw = 0.02;

%% Motor limits

T_motor_min = 0.0;
T_motor_max = 7.5;

%% ============================================================
% CLASSICAL PD GAINS
% ============================================================

Kp_x = 1.0;
Kd_x = 1.4;

Kp_y = 1.0;
Kd_y = 1.4;

Kp_z = 4.0;
Kd_z = 3.0;

Kp_phi = 0.8;
Kd_phi = 0.25;

Kp_theta = 0.8;
Kd_theta = 0.25;

Kp_psi = 0.5;
Kd_psi = 0.20;

%% ============================================================
% NOMINAL LINEAR MODEL FOR LQR/LQI
% ============================================================

A = zeros(12);

A(1,4) = 1;
A(2,5) = 1;
A(3,6) = 1;

A(4,8) = g;
A(5,7) = -g;

A(7,10) = 1;
A(8,11) = 1;
A(9,12) = 1;

B = zeros(12,4);

B(6,1) = 1/m_nominal;

B(10,2) = 1/Ix_nominal;
B(11,3) = 1/Iy_nominal;
B(12,4) = 1/Iz_nominal;

%% ============================================================
% LQR DESIGN
% ============================================================

Q = diag([ ...
    20,20,30, ...
    5,5,8, ...
    40,40,10, ...
    2,2,2]);

R = diag([ ...
    1.0, ...
    0.5, ...
    0.5, ...
    0.5]);

K_lqr = lqr(A,B,Q,R);

%% ============================================================
% LQI DESIGN
% ============================================================

C_pos = zeros(3,12);

C_pos(1,1) = 1;
C_pos(2,2) = 1;
C_pos(3,3) = 1;

A_aug = zeros(15,15);

A_aug(1:12,1:12) = A;
A_aug(13:15,1:12) = -C_pos;

B_aug = zeros(15,4);

B_aug(1:12,:) = B;

Q_aug = diag([ ...
    20,20,30, ...
    5,5,8, ...
    40,40,10, ...
    2,2,2, ...
    20,20,25]);

K_aug = lqr( ...
    A_aug, ...
    B_aug, ...
    Q_aug, ...
    R);

Kx_lqi = K_aug(:,1:12);
Ki_lqi = K_aug(:,13:15);

%% ============================================================
% INITIAL CONDITION
% ============================================================

% Start exactly at reference to isolate robustness performance

x0 = zeros(12,1);

x0(1) = x_des;
x0(2) = y_des;
x0(3) = z_des;

x0_lqi = zeros(15,1);

x0_lqi(1:12) = x0;

%% ============================================================
% RESULT ARRAYS
% ============================================================

RMSE_PD  = zeros(N_runs,1);
RMSE_LQR = zeros(N_runs,1);
RMSE_LQI = zeros(N_runs,1);

FINAL_PD  = zeros(N_runs,1);
FINAL_LQR = zeros(N_runs,1);
FINAL_LQI = zeros(N_runs,1);

PEAK_PD  = zeros(N_runs,1);
PEAK_LQR = zeros(N_runs,1);
PEAK_LQI = zeros(N_runs,1);

SAT_PD  = zeros(N_runs,1);
SAT_LQR = zeros(N_runs,1);
SAT_LQI = zeros(N_runs,1);

mass_actual_log = zeros(N_runs,1);
wind_mag_log = zeros(N_runs,1);
wind_angle_log = zeros(N_runs,1);

%% ============================================================
% COMMON ODE SETTINGS
% ============================================================

options = odeset( ...
    'RelTol',1e-5, ...
    'AbsTol',1e-7);

t_eval = linspace( ...
    t_start, ...
    t_end, ...
    1001)';

fprintf('============================================\n');
fprintf('AeroStabilize Monte-Carlo Robustness Test\n');
fprintf('============================================\n');
fprintf('Runs: %d\n\n',N_runs);

%% ============================================================
% MONTE-CARLO LOOP
% ============================================================

for run = 1:N_runs

    %% --------------------------------------------------------
    % RANDOM PLANT PARAMETERS
    % ---------------------------------------------------------

    mass_scale = ...
        1 + (-0.20 + 0.40*rand);

    m_actual = ...
        m_nominal*mass_scale;

    Ix_actual = ...
        Ix_nominal*(1 + (-0.15 + 0.30*rand));

    Iy_actual = ...
        Iy_nominal*(1 + (-0.15 + 0.30*rand));

    Iz_actual = ...
        Iz_nominal*(1 + (-0.15 + 0.30*rand));

    I_actual = diag([ ...
        Ix_actual, ...
        Iy_actual, ...
        Iz_actual]);

    %% --------------------------------------------------------
    % RANDOM WIND
    % ---------------------------------------------------------

    wind_mag = ...
        5.0*rand;

    wind_angle = ...
        2*pi*rand;

    F_wind = [ ...
        wind_mag*cos(wind_angle);
        wind_mag*sin(wind_angle);
        0];

    mass_actual_log(run) = m_actual;
    wind_mag_log(run) = wind_mag;
    wind_angle_log(run) = wind_angle;

    %% ========================================================
    % PD
    % ========================================================

    ode_pd = @(t,x) dynamics_pd_mc( ...
        t, ...
        x, ...
        x_des, ...
        y_des, ...
        z_des, ...
        Kp_x, ...
        Kd_x, ...
        Kp_y, ...
        Kd_y, ...
        Kp_z, ...
        Kd_z, ...
        Kp_phi, ...
        Kd_phi, ...
        Kp_theta, ...
        Kd_theta, ...
        Kp_psi, ...
        Kd_psi, ...
        m_nominal, ...
        m_actual, ...
        F_wind, ...
        wind_start, ...
        g, ...
        I_actual, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    [t_pd,X_pd] = ode45( ...
        ode_pd, ...
        [t_start t_end], ...
        x0, ...
        options);

    Xpd = interp1( ...
        t_pd, ...
        X_pd, ...
        t_eval, ...
        'linear');

    %% ========================================================
    % LQR
    % ========================================================

    ode_lqr = @(t,x) dynamics_lqr_mc( ...
        t, ...
        x, ...
        K_lqr, ...
        x_des, ...
        y_des, ...
        z_des, ...
        m_nominal, ...
        m_actual, ...
        F_wind, ...
        wind_start, ...
        g, ...
        I_actual, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    [t_lqr,X_lqr] = ode45( ...
        ode_lqr, ...
        [t_start t_end], ...
        x0, ...
        options);

    Xlqr = interp1( ...
        t_lqr, ...
        X_lqr, ...
        t_eval, ...
        'linear');

    %% ========================================================
    % LQI
    % ========================================================

    ode_lqi = @(t,x) dynamics_lqi_mc( ...
        t, ...
        x, ...
        Kx_lqi, ...
        Ki_lqi, ...
        x_des, ...
        y_des, ...
        z_des, ...
        m_nominal, ...
        m_actual, ...
        F_wind, ...
        wind_start, ...
        g, ...
        I_actual, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    [t_lqi,X_lqi] = ode45( ...
        ode_lqi, ...
        [t_start t_end], ...
        x0_lqi, ...
        options);

    Xlqi = interp1( ...
        t_lqi, ...
        X_lqi, ...
        t_eval, ...
        'linear');

    %% ========================================================
    % ERRORS
    % ========================================================

    ref = [ ...
        x_des, ...
        y_des, ...
        z_des];

    err_pd_xyz = ...
        ref - Xpd(:,1:3);

    err_lqr_xyz = ...
        ref - Xlqr(:,1:3);

    err_lqi_xyz = ...
        ref - Xlqi(:,1:3);

    err_pd = sqrt( ...
        sum(err_pd_xyz.^2,2));

    err_lqr = sqrt( ...
        sum(err_lqr_xyz.^2,2));

    err_lqi = sqrt( ...
        sum(err_lqi_xyz.^2,2));

    %% Evaluate only after disturbance begins

    idx_eval = ...
        t_eval >= wind_start;

    RMSE_PD(run) = sqrt( ...
        mean(err_pd(idx_eval).^2));

    RMSE_LQR(run) = sqrt( ...
        mean(err_lqr(idx_eval).^2));

    RMSE_LQI(run) = sqrt( ...
        mean(err_lqi(idx_eval).^2));

    FINAL_PD(run) = err_pd(end);
    FINAL_LQR(run) = err_lqr(end);
    FINAL_LQI(run) = err_lqi(end);

    PEAK_PD(run) = max( ...
        err_pd(idx_eval));

    PEAK_LQR(run) = max( ...
        err_lqr(idx_eval));

    PEAK_LQI(run) = max( ...
        err_lqi(idx_eval));

    %% ========================================================
    % SATURATION PERCENTAGE
    % ========================================================

    SAT_PD(run) = saturation_percentage_pd( ...
        t_eval, ...
        Xpd, ...
        x_des, ...
        y_des, ...
        z_des, ...
        Kp_x, ...
        Kd_x, ...
        Kp_y, ...
        Kd_y, ...
        Kp_z, ...
        Kd_z, ...
        Kp_phi, ...
        Kd_phi, ...
        Kp_theta, ...
        Kd_theta, ...
        Kp_psi, ...
        Kd_psi, ...
        m_nominal, ...
        g, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    SAT_LQR(run) = saturation_percentage_lqr( ...
        t_eval, ...
        Xlqr, ...
        K_lqr, ...
        x_des, ...
        y_des, ...
        z_des, ...
        m_nominal, ...
        g, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    SAT_LQI(run) = saturation_percentage_lqi( ...
        t_eval, ...
        Xlqi, ...
        Kx_lqi, ...
        Ki_lqi, ...
        x_des, ...
        y_des, ...
        z_des, ...
        m_nominal, ...
        g, ...
        L, ...
        k_yaw, ...
        T_motor_min, ...
        T_motor_max);

    %% Progress

    if mod(run,10) == 0

        fprintf( ...
            'Completed %d / %d runs\n', ...
            run, ...
            N_runs);

    end

end

%% ============================================================
% STATISTICS
% ============================================================

mean_rmse = [ ...
