%% ============================================================
% LOCAL FUNCTION: PD DYNAMICS
% ============================================================

function dx = dynamics_pd_mc( ...
    t,state, ...
    x_des,y_des,z_des, ...
    Kp_x,Kd_x, ...
    Kp_y,Kd_y, ...
    Kp_z,Kd_z, ...
    Kp_phi,Kd_phi, ...
    Kp_theta,Kd_theta, ...
    Kp_psi,Kd_psi, ...
    m_nominal,m_actual, ...
    F_wind,wind_start, ...
    g,I,L,k_yaw,Tmin,Tmax)

x = state(1);
y = state(2);
z = state(3);

vx = state(4);
vy = state(5);
vz = state(6);

phi = state(7);
theta = state(8);
psi = state(9);

p = state(10);
q = state(11);
r = state(12);

ex = x_des-x;
ey = y_des-y;
ez = z_des-z;

ax_des = ...
    Kp_x*ex - ...
    Kd_x*vx;

ay_des = ...
    Kp_y*ey - ...
    Kd_y*vy;

theta_des = ax_des/g;
phi_des = -ay_des/g;

T_cmd = ...
    m_nominal*g + ...
    Kp_z*ez - ...
    Kd_z*vz;

tau_phi = ...
    Kp_phi*(phi_des-phi) - ...
    Kd_phi*p;

tau_theta = ...
    Kp_theta*(theta_des-theta) - ...
    Kd_theta*q;

tau_psi = ...
    Kp_psi*(0-psi) - ...
    Kd_psi*r;

u_cmd = [ ...
    T_cmd;
    tau_phi;
    tau_theta;
    tau_psi];

if t >= wind_start
    F_ext = F_wind;
else
    F_ext = [0;0;0];
end

dx = plant_mc( ...
    state, ...
    u_cmd, ...
    m_actual, ...
    I, ...
    F_ext, ...
    g,L,k_yaw,Tmin,Tmax);

end

%% ============================================================
% LQR DYNAMICS
% ============================================================

function dx = dynamics_lqr_mc( ...
    t,state,K, ...
    x_des,y_des,z_des, ...
    m_nominal,m_actual, ...
    F_wind,wind_start, ...
    g,I,L,k_yaw,Tmin,Tmax)

x_ref = zeros(12,1);

x_ref(1) = x_des;
x_ref(2) = y_des;
x_ref(3) = z_des;

e = state-x_ref;

delta_u = -K*e;

u_cmd = [ ...
    m_nominal*g;
    0;
    0;
    0] + delta_u;

if t >= wind_start
    F_ext = F_wind;
else
    F_ext = [0;0;0];
end

dx = plant_mc( ...
    state, ...
    u_cmd, ...
    m_actual, ...
    I, ...
    F_ext, ...
    g,L,k_yaw,Tmin,Tmax);

end

%% ============================================================
% LQI DYNAMICS
% ============================================================

function dx_aug = dynamics_lqi_mc( ...
    t,x_aug,Kx,Ki, ...
    x_des,y_des,z_des, ...
    m_nominal,m_actual, ...
    F_wind,wind_start, ...
    g,I,L,k_yaw,Tmin,Tmax)

state = x_aug(1:12);

xi = x_aug(13:15);

x_ref = zeros(12,1);

x_ref(1) = x_des;
x_ref(2) = y_des;
x_ref(3) = z_des;

e = state-x_ref;

delta_u = ...
    -Kx*e - ...
    Ki*xi;

u_cmd = [ ...
    m_nominal*g;
    0;
    0;
    0] + delta_u;

if t >= wind_start
    F_ext = F_wind;
else
    F_ext = [0;0;0];
end

dx = plant_mc( ...
    state, ...
    u_cmd, ...
    m_actual, ...
    I, ...
    F_ext, ...
    g,L,k_yaw,Tmin,Tmax);

xi_dot = [ ...
    x_des-state(1);
    y_des-state(2);
    z_des-state(3)];

dx_aug = [ ...
    dx;
    xi_dot];

end

%% ============================================================
% NONLINEAR PLANT
% ============================================================

function dx = plant_mc( ...
    state,u_cmd,m,I,F_ext, ...
    g,L,k_yaw,Tmin,Tmax)

vx = state(4);
vy = state(5);
vz = state(6);

phi = state(7);
theta = state(8);
psi = state(9);

p = state(10);
q = state(11);
r = state(12);

M = [ ...
    1,1,1,1;
    0,L,0,-L;
    -L,0,L,0;
    k_yaw,-k_yaw,k_yaw,-k_yaw];

motors = M\u_cmd;

motors = min( ...
    max(motors,Tmin), ...
    Tmax);

u_actual = M*motors;

T = u_actual(1);
tau = u_actual(2:4);

Rx = [ ...
    1,0,0;
    0,cos(phi),-sin(phi);
    0,sin(phi),cos(phi)];

Ry = [ ...
    cos(theta),0,sin(theta);
    0,1,0;
    -sin(theta),0,cos(theta)];

Rz = [ ...
    cos(psi),-sin(psi),0;
    sin(psi),cos(psi),0;
    0,0,1];

Rbw = Rz*Ry*Rx;

F_thrust = Rbw*[0;0;T];

F_gravity = [0;0;-m*g];

acc = ( ...
    F_thrust + ...
    F_gravity + ...
    F_ext)/m;

omega = [p;q;r];

omega_dot = I \ ( ...
    tau - ...
    cross(omega,I*omega));

E = [ ...
    1, ...
    sin(phi)*tan(theta), ...
    cos(phi)*tan(theta);
    0, ...
    cos(phi), ...
    -sin(phi);
    0, ...
    sin(phi)/cos(theta), ...
    cos(phi)/cos(theta)];

euler_dot = E*omega;

dx = zeros(12,1);

dx(1:3) = [vx;vy;vz];

dx(4:6) = acc;

dx(7:9) = euler_dot;

dx(10:12) = omega_dot;

end

%% ============================================================
% SATURATION: PD
% ============================================================

function pct = saturation_percentage_pd( ...
    t,X, ...
    x_des,y_des,z_des, ...
    Kp_x,Kd_x, ...
    Kp_y,Kd_y, ...
    Kp_z,Kd_z, ...
    Kp_phi,Kd_phi, ...
    Kp_theta,Kd_theta, ...
    Kp_psi,Kd_psi, ...
    m_nominal,g,L,k_yaw,Tmin,Tmax)

N = length(t);

sat = false(N,1);

M = [ ...
    1,1,1,1;
    0,L,0,-L;
    -L,0,L,0;
    k_yaw,-k_yaw,k_yaw,-k_yaw];

for k = 1:N

    s = X(k,:)';

    ex = x_des-s(1);
    ey = y_des-s(2);
    ez = z_des-s(3);

    ax_des = ...
        Kp_x*ex - ...
        Kd_x*s(4);

    ay_des = ...
        Kp_y*ey - ...
        Kd_y*s(5);

    theta_des = ax_des/g;
    phi_des = -ay_des/g;

    T_cmd = ...
        m_nominal*g + ...
        Kp_z*ez - ...
        Kd_z*s(6);

    tau_phi = ...
        Kp_phi*(phi_des-s(7)) - ...
        Kd_phi*s(10);

    tau_theta = ...
        Kp_theta*(theta_des-s(8)) - ...
        Kd_theta*s(11);

    tau_psi = ...
        Kp_psi*(0-s(9)) - ...
        Kd_psi*s(12);

    requested = M \ [ ...
        T_cmd;
        tau_phi;
        tau_theta;
        tau_psi];

    sat(k) = any( ...
        requested<Tmin | ...
        requested>Tmax);

end

duration = trapz( ...
    t, ...
    double(sat));

pct = ...
    100*duration/(t(end)-t(1));

end

