        0;
        0] - ...
        Kx*(state-x_ref) - ...
        Ki*xi;

    requested = M\u_cmd;

    sat(k) = any( ...
        requested<Tmin | ...
        requested>Tmax);

end

duration = trapz( ...
    t, ...
