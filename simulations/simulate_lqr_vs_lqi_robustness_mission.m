% RESULTS
% ============================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('OVERALL PERFORMANCE\n');
fprintf('============================================\n');

fprintf('LQR RMSE: %.6f m\n',rmse_lqr_all);
fprintf('LQI RMSE: %.6f m\n',rmse_lqi_all);

