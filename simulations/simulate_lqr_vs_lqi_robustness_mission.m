%% AeroStabilize
% LQR + FF vs 3-Axis LQI + FF
% Final Robustness Mission
%
% Mission:
%   0 - 8 s   : Nominal 3D Figure-8 tracking
%   8 - 10 s  : +5 N X wind gust
%   14 - 16 s : -4 N Y wind gust
%   t = 20 s  : Payload increase 1.5 kg -> 1.8 kg
%   26 - 34 s : Constant diagonal wind
%   34 - 40 s : Wind removed, recovery
%
% Both controllers use:
%   - Same nonlinear 6-DOF plant
%   - Same trajectory
%   - Same initial condition
%   - Same actuator limits
%   - Same disturbances
%
% Goal:
% Demonstrate transient robustness and steady-state
% disturbance rejection.

clear;
clc;
close all;

%% ============================================================
% PARAMETERS
% ============================================================

g = 9.81;

m_nominal = 1.5;
m_payload = 1.8;

L = 0.225;

Ix = 0.020;
Iy = 0.020;
Iz = 0.040;

I = diag([Ix Iy Iz]);

k_yaw = 0.02;

%% Motor limits

T_motor_min = 0.0;
T_motor_max = 7.5;

%% ============================================================
% FIGURE-8 TRAJECTORY PARAMETERS
% ============================================================

A_traj = 2.0;     % X amplitude [m]
B_traj = 1.5;     % Y amplitude [m]

omega_traj = 0.30;

z0_traj = 2.0;
C_traj  = 0.50;

%% ============================================================
% MISSION EVENTS
% ============================================================

gust_x_start = 8.0;
gust_x_end   = 10.0;

gust_y_start = 14.0;
gust_y_end   = 16.0;

payload_time = 20.0;

crosswind_start = 26.0;
crosswind_end   = 34.0;

%% Disturbance forces

F_gust_x = [ ...
    5.0;
    0.0;
    0.0];

F_gust_y = [ ...
    0.0;
   -4.0;
    0.0];

F_crosswind = [ ...
    2.0;
   -2.0;
    0.0];

%% ============================================================
% SIMULATION SETTINGS
% ============================================================

t_start = 0;
t_end   = 40;

%% ============================================================
% LINEARIZED HOVER MODEL
% ============================================================

A = zeros(12);

% Position kinematics
A(1,4) = 1;
A(2,5) = 1;
A(3,6) = 1;

% Translational coupling
A(4,8) = g;
A(5,7) = -g;

% Euler kinematics
A(7,10) = 1;
A(8,11) = 1;
A(9,12) = 1;

B = zeros(12,4);

B(6,1) = 1/m_nominal;

B(10,2) = 1/Ix;
B(11,3) = 1/Iy;
B(12,4) = 1/Iz;

%% ============================================================
% LQR DESIGN
% ============================================================

Q = diag([ ...
    20, ...
    20, ...
    30, ...
    5, ...
    5, ...
    8, ...
    40, ...
    40, ...
    10, ...
    2, ...
    2, ...
    2]);

R = diag([ ...
    1.0, ...
    0.5, ...
    0.5, ...
    0.5]);

K_lqr = lqr(A,B,Q,R);

%% ============================================================
% 3-AXIS LQI DESIGN
% ============================================================

C_pos = zeros(3,12);

C_pos(1,1) = 1;
C_pos(2,2) = 1;
C_pos(3,3) = 1;

A_aug = zeros(15,15);

A_aug(1:12,1:12) = A;

% xi_dot = desired - actual
A_aug(13:15,1:12) = -C_pos;

B_aug = zeros(15,4);
B_aug(1:12,:) = B;

Q_aug = diag([ ...
    20, ...
    20, ...
    30, ...
    5, ...
    5, ...
    8, ...
    40, ...
    40, ...
    10, ...
    2, ...
    2, ...
    2, ...
    20, ...
    20, ...
    25]);

K_aug = lqr( ...
    A_aug, ...
    B_aug, ...
    Q_aug, ...
    R);

Kx_lqi = K_aug(:,1:12);

Ki_lqi = K_aug(:,13:15);

%% ============================================================
% CONTROLLABILITY
% ============================================================

rank_lqr = rank(ctrb(A,B));

rank_lqi = rank(ctrb(A_aug,B_aug));

fprintf('============================================\n');
fprintf('AeroStabilize Final Robustness Mission\n');
fprintf('============================================\n');

fprintf('LQR controllability: %d / 12\n',rank_lqr);
fprintf('LQI controllability: %d / 15\n',rank_lqi);

%% ============================================================
% INITIAL CONDITION
% ============================================================

[ ...
    xd0, ...
    yd0, ...
    zd0, ...
    vxd0, ...
    vyd0, ...
    vzd0, ...
    ax0, ...
    ay0, ...
    ~] = figure8_reference( ...
    0, ...
    A_traj, ...
    B_traj, ...
    omega_traj, ...
    z0_traj, ...
    C_traj);

theta_ff_0 = ax0/g;
phi_ff_0   = -ay0/g;

x0 = zeros(12,1);

x0(1) = xd0;
x0(2) = yd0;
x0(3) = zd0;

x0(4) = vxd0;
x0(5) = vyd0;
x0(6) = vzd0;

x0(7) = phi_ff_0;
x0(8) = theta_ff_0;

%% LQI initial state

x0_lqi = zeros(15,1);

x0_lqi(1:12) = x0;

%% ============================================================
% ODE OPTIONS
% ============================================================

options = odeset( ...
    'RelTol',1e-7, ...
    'AbsTol',1e-9);

%% ============================================================
% RUN LQR
% ============================================================

ode_lqr = @(t,x) mission_lqr_dynamics( ...
    t, ...
    x, ...
    K_lqr, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max, ...
    A_traj, ...
    B_traj, ...
    omega_traj, ...
    z0_traj, ...
    C_traj, ...
    gust_x_start, ...
    gust_x_end, ...
    gust_y_start, ...
    gust_y_end, ...
    crosswind_start, ...
    crosswind_end, ...
    F_gust_x, ...
    F_gust_y, ...
    F_crosswind);

[t_lqr,X_lqr] = ode45( ...
    ode_lqr, ...
    [t_start t_end], ...
    x0, ...
    options);

%% ============================================================
% RUN LQI
% ============================================================

ode_lqi = @(t,x) mission_lqi_dynamics( ...
    t, ...
    x, ...
    Kx_lqi, ...
    Ki_lqi, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max, ...
    A_traj, ...
    B_traj, ...
    omega_traj, ...
    z0_traj, ...
    C_traj, ...
    gust_x_start, ...
    gust_x_end, ...
    gust_y_start, ...
    gust_y_end, ...
    crosswind_start, ...
    crosswind_end, ...
    F_gust_x, ...
    F_gust_y, ...
    F_crosswind);

[t_lqi,X_lqi] = ode45( ...
    ode_lqi, ...
    [t_start t_end], ...
    x0_lqi, ...
    options);

%% ============================================================
% COMMON TIME VECTOR
% ============================================================

t = linspace( ...
    t_start, ...
    t_end, ...
    4001)';

Xlqr = interp1( ...
    t_lqr, ...
    X_lqr, ...
    t, ...
    'linear');

Xlqi = interp1( ...
    t_lqi, ...
    X_lqi, ...
    t, ...
    'linear');

%% ============================================================
% REFERENCE TRAJECTORY
% ============================================================

N = length(t);

ref = zeros(N,9);

for k = 1:N

    [ ...
        ref(k,1), ...
        ref(k,2), ...
        ref(k,3), ...
        ref(k,4), ...
        ref(k,5), ...
        ref(k,6), ...
        ref(k,7), ...
        ref(k,8), ...
        ref(k,9)] = figure8_reference( ...
        t(k), ...
        A_traj, ...
        B_traj, ...
        omega_traj, ...
        z0_traj, ...
        C_traj);

end

%% ============================================================
% POSITION ERRORS
% ============================================================

error_xyz_lqr = ...
    ref(:,1:3) - Xlqr(:,1:3);

error_xyz_lqi = ...
    ref(:,1:3) - Xlqi(:,1:3);

error_lqr = sqrt( ...
    sum(error_xyz_lqr.^2,2));

error_lqi = sqrt( ...
    sum(error_xyz_lqi.^2,2));

%% ============================================================
% CONTROL HISTORY
% ============================================================

[ ...
    motor_lqr, ...
    thrust_lqr, ...
    saturation_lqr] = reconstruct_mission_lqr( ...
    t, ...
    Xlqr, ...
    K_lqr, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max, ...
    A_traj, ...
    B_traj, ...
    omega_traj, ...
    z0_traj, ...
    C_traj);

[ ...
    motor_lqi, ...
    thrust_lqi, ...
    saturation_lqi] = reconstruct_mission_lqi( ...
    t, ...
    Xlqi, ...
    Kx_lqi, ...
    Ki_lqi, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max, ...
    A_traj, ...
    B_traj, ...
    omega_traj, ...
    z0_traj, ...
    C_traj);

%% ============================================================
% PERFORMANCE WINDOWS
% ============================================================

idx_nominal = t < gust_x_start;

idx_gust_x = ...
    t >= gust_x_start & ...
    t <= 12;

idx_gust_y = ...
    t >= gust_y_start & ...
    t <= 18;

idx_payload = ...
    t >= payload_time & ...
    t < crosswind_start;

idx_crosswind = ...
    t >= crosswind_start & ...
    t < crosswind_end;

idx_recovery = ...
    t >= crosswind_end;

%% ============================================================
% RMSE VALUES
% ============================================================

rmse_lqr_all = sqrt(mean(error_lqr.^2));
rmse_lqi_all = sqrt(mean(error_lqi.^2));

rmse_lqr_nominal = sqrt( ...
    mean(error_lqr(idx_nominal).^2));

rmse_lqi_nominal = sqrt( ...
    mean(error_lqi(idx_nominal).^2));

rmse_lqr_payload = sqrt( ...
    mean(error_lqr(idx_payload).^2));

rmse_lqi_payload = sqrt( ...
    mean(error_lqi(idx_payload).^2));

rmse_lqr_crosswind = sqrt( ...
    mean(error_lqr(idx_crosswind).^2));

rmse_lqi_crosswind = sqrt( ...
    mean(error_lqi(idx_crosswind).^2));

rmse_lqr_recovery = sqrt( ...
    mean(error_lqr(idx_recovery).^2));

rmse_lqi_recovery = sqrt( ...
    mean(error_lqi(idx_recovery).^2));

%% ============================================================
% PEAK ERRORS
% ============================================================

peak_lqr_gust_x = max(error_lqr(idx_gust_x));
peak_lqi_gust_x = max(error_lqi(idx_gust_x));

peak_lqr_gust_y = max(error_lqr(idx_gust_y));
peak_lqi_gust_y = max(error_lqi(idx_gust_y));

peak_lqr_crosswind = max(error_lqr(idx_crosswind));
peak_lqi_crosswind = max(error_lqi(idx_crosswind));

%% ============================================================
% FINAL ERROR
% ============================================================

final_lqr = error_lqr(end);
final_lqi = error_lqi(end);

final_xyz_lqr = error_xyz_lqr(end,:);
final_xyz_lqi = error_xyz_lqi(end,:);

