% LOCAL FUNCTION: FIGURE-8 TRAJECTORY
% ============================================================

function [ ...
    x, ...
    y, ...
    z, ...
    vx, ...
    vy, ...
    vz, ...
    ax, ...
    ay, ...
    az] = figure8_reference( ...
    t, ...
    A, ...
    B, ...
    omega, ...
    z0, ...
    C)

%% Position

x = A*sin(omega*t);

y = B*sin(2*omega*t);

z = z0 + C*sin(0.5*omega*t);

%% Velocity

vx = A*omega*cos(omega*t);

vy = 2*B*omega*cos(2*omega*t);

vz = 0.5*C*omega*cos(0.5*omega*t);

%% Acceleration

ax = -A*omega^2*sin(omega*t);

ay = -4*B*omega^2*sin(2*omega*t);

az = -0.25*C*omega^2*sin(0.5*omega*t);

end

%% ============================================================
% LOCAL FUNCTION: EXTERNAL FORCE
% ============================================================

function F = mission_disturbance( ...
    t, ...
    gust_x_start, ...
    gust_x_end, ...
    gust_y_start, ...
    gust_y_end, ...
    crosswind_start, ...
    crosswind_end, ...
    F_gust_x, ...
    F_gust_y, ...
    F_crosswind)

F = [0;0;0];

if t >= gust_x_start && t <= gust_x_end

    F = F + F_gust_x;

end

if t >= gust_y_start && t <= gust_y_end

    F = F + F_gust_y;

end

if t >= crosswind_start && t <= crosswind_end

    F = F + F_crosswind;

end

end

%% ============================================================
% LOCAL FUNCTION: ACTUAL MASS
% ============================================================

function m_actual = mission_mass( ...
    t, ...
    m_nominal, ...
    m_payload, ...
    payload_time)

if t < payload_time

    m_actual = m_nominal;

else

    m_actual = m_payload;

end

end

