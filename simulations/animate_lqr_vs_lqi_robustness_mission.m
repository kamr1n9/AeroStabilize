    % ---------------------------------------------------------

    state_lqi = Xlqi_anim(k,1:12)';

    update_drone( ...
        state_lqi, ...
        Xlqi_anim(:,1:12), ...
        k, ...
        ref_anim(k,:), ...
        F_current, ...
        path_lqi, ...
        desired_lqi, ...
        arm1_lqi, ...
        arm2_lqi, ...
        body_lqi, ...
        rotor_lqi, ...
