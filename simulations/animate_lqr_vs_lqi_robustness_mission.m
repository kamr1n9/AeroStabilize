function dx = lqr_dynamics( ...
    t,state,K, ...
    m_nominal,m_payload,payload_time, ...
    g,I,L,k_yaw,Tmin,Tmax, ...
    At,Bt,wt,z0,Ct, ...
    gx1,gx2,gy1,gy2,cw1,cw2, ...
    Fx,Fy,Fc)

