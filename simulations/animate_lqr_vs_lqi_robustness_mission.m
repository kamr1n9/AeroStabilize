        arm_x_body, ...
        arm_y_body, ...
        rotor_centers_body, ...
        rotor_radius, ...
        rotor_angle);

    %% --------------------------------------------------------
    % Status LQR
    % ---------------------------------------------------------

    status_string_lqr = sprintf([ ...
        'Time:      %5.1f s\n' ...
        '3D error:  %6.3f m\n' ...
        'Z error:   %6.3f m\n' ...
        'Mass:      %4.2f kg\n' ...
        'Thrust:    %6.2f N\n' ...
        'Roll:      %6.2f deg\n' ...
        'Pitch:     %6.2f deg'], ...
        tk, ...
        error_lqr_anim(k), ...
        error_xyz_lqr_anim(k,3), ...
        mass_current, ...
        thrust_lqr_anim(k), ...
        rad2deg(state_lqr(7)), ...
        rad2deg(state_lqr(8)));

    if isgraphics(status_lqr)

        set( ...
            status_lqr, ...
            'String',status_string_lqr);

    end

    %% --------------------------------------------------------
    % Status LQI
    % ---------------------------------------------------------

    status_string_lqi = sprintf([ ...
        'Time:      %5.1f s\n' ...
        '3D error:  %6.3f m\n' ...
        'Z error:   %6.3f m\n' ...
        'Mass:      %4.2f kg\n' ...
        'Thrust:    %6.2f N\n' ...
        'xi_x:      %6.3f\n' ...
        'xi_y:      %6.3f\n' ...
        'xi_z:      %6.3f'], ...
        tk, ...
        error_lqi_anim(k), ...
        error_xyz_lqi_anim(k,3), ...
        mass_current, ...
        thrust_lqi_anim(k), ...
        xi_lqi_anim(k,1), ...
        xi_lqi_anim(k,2), ...
        xi_lqi_anim(k,3));

    if isgraphics(status_lqi)

        set( ...
            status_lqi, ...
            'String',status_string_lqi);

    end

    %% --------------------------------------------------------
    % Error markers
    % ---------------------------------------------------------

    if isgraphics(error_marker_lqr)

        set( ...
            error_marker_lqr, ...
            'XData',tk, ...
            'YData',error_lqr_anim(k));

    end

    if isgraphics(error_marker_lqi)

        set( ...
            error_marker_lqi, ...
            'XData',tk, ...
            'YData',error_lqi_anim(k));

    end

    %% --------------------------------------------------------
    % Motor bars
    % ---------------------------------------------------------

    if isgraphics(motor_bar)

        motor_bar.YData = [ ...
            motor_lqr_anim(k,:), ...
            motor_lqi_anim(k,:)];

    end

    drawnow limitrate;

    pause(frame_dt/animation_speed);

end

%% ============================================================
% LOCAL FUNCTION: UPDATE DRONE
% ============================================================

function update_drone( ...
    state, ...
    state_history, ...
    k, ...
    ref_current, ...
    F_current, ...
    path_handle, ...
    desired_handle, ...
    arm1_handle, ...
    arm2_handle, ...
    body_handle, ...
    rotor_handles, ...
    wind_handle, ...
    arm_x_body, ...
    arm_y_body, ...
    rotor_centers_body, ...
    rotor_radius, ...
    rotor_angle)

pos = state(1:3);

phi = state(7);
theta = state(8);
psi = state(9);

Rx = [ ...
    1,0,0;
    0,cos(phi),-sin(phi);
    0,sin(phi),cos(phi)];

Ry = [ ...
    cos(theta),0,sin(theta);
    0,1,0;
    -sin(theta),0,cos(theta)];

Rz = [ ...
    cos(psi),-sin(psi),0;
    sin(psi),cos(psi),0;
    0,0,1];

Rbw = Rz*Ry*Rx;

%% Path

if isgraphics(path_handle)

    set( ...
        path_handle, ...
        'XData',state_history(1:k,1), ...
        'YData',state_history(1:k,2), ...
        'ZData',state_history(1:k,3));

end

%% Desired point

if isgraphics(desired_handle)

    set( ...
        desired_handle, ...
        'XData',ref_current(1), ...
        'YData',ref_current(2), ...
        'ZData',ref_current(3));

end

%% Arms

arm1_world = Rbw*arm_x_body + pos;

arm2_world = Rbw*arm_y_body + pos;

if isgraphics(arm1_handle)

    set( ...
        arm1_handle, ...
        'XData',arm1_world(1,:), ...
        'YData',arm1_world(2,:), ...
        'ZData',arm1_world(3,:));

end

if isgraphics(arm2_handle)

    set( ...
        arm2_handle, ...
        'XData',arm2_world(1,:), ...
        'YData',arm2_world(2,:), ...
