    mass = m_payload;
end

F = [0;0;0];

if t >= gx1 && t <= gx2

    F = Fx;
    event = '+5 N X GUST';

elseif t >= gy1 && t <= gy2

    F = Fy;
    event = '-4 N Y GUST';

elseif t >= cw1 && t <= cw2

    F = Fc;
    event = 'DIAGONAL CROSSWIND';

elseif t >= payload_time && t < cw1

