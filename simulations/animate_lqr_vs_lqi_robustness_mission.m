x_ref = zeros(12,1);

x_ref(1:6) = [ ...
    xd;yd;zd; ...
    vxd;vyd;vzd];

x_ref(7) = phi_ff;
x_ref(8) = theta_ff;

delta_u = -K*(state-x_ref);

u_cmd = [ ...
    m_nominal*(g+az);
    0;
    0;
    0] + delta_u;

m = actual_mass( ...
    t, ...
    m_nominal, ...
    m_payload, ...
    payload_time);

F = disturbance_force( ...
    t, ...
    gx1,gx2, ...
    gy1,gy2, ...
    cw1,cw2, ...
    Fx,Fy,Fc);

dx = plant( ...
    state, ...
    u_cmd, ...
    m, ...
    F, ...
    g,I,L,k_yaw,Tmin,Tmax);

end

