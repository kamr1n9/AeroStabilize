elseif t > cw2

    event = 'FINAL RECOVERY';

else

    event = 'NOMINAL FLIGHT';

end

end

%% ============================================================
% FIGURE-8 REFERENCE
% ============================================================

function [x,y,z,vx,vy,vz,ax,ay,az] = ...
    figure8_reference(t,A,B,w,z0,C)

x = A*sin(w*t);

y = B*sin(2*w*t);

z = z0 + C*sin(0.5*w*t);

vx = A*w*cos(w*t);

vy = 2*B*w*cos(2*w*t);

vz = 0.5*C*w*cos(0.5*w*t);

ax = -A*w^2*sin(w*t);

ay = -4*B*w^2*sin(2*w*t);

az = -0.25*C*w^2*sin(0.5*w*t);

end

