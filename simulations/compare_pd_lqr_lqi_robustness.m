%% AeroStabilize
% PD + FF vs LQR + FF vs 3-Axis LQI + FF
%
% Fair robustness comparison under identical conditions.
%
% Scenario:
%   0 - 10 s : nominal hover at [1 1 2] m
%   t = 10 s : constant +2 N X disturbance begins
%   t = 20 s : mass changes from 1.5 kg to 1.8 kg
%   20 - 35 s: wind + payload mismatch both remain active
%
% All controllers:
%   - Same nonlinear 6-DOF plant
%   - Same motor mixer
%   - Same motor limits
%   - Same initial condition
%   - Same disturbances
%
% Goal:
% Compare steady-state disturbance rejection and model-mismatch
% compensation.

clear;
clc;
close all;

%% ============================================================
% PARAMETERS
% ============================================================

g = 9.81;

m_nominal = 1.5;
m_payload = 1.8;

L = 0.225;

Ix = 0.020;
Iy = 0.020;
Iz = 0.040;

I = diag([Ix Iy Iz]);

k_yaw = 0.02;

%% Motor limits

T_motor_min = 0.0;
T_motor_max = 7.5;

%% ============================================================
% DESIRED POSITION
% ============================================================

x_des = 1.0;
y_des = 1.0;
z_des = 2.0;

%% ============================================================
% DISTURBANCE SCHEDULE
% ============================================================

wind_start = 10.0;

payload_time = 20.0;

F_wind = [ ...
    2.0;
    0.0;
    0.0];

%% ============================================================
% SIMULATION SETTINGS
% ============================================================

t_start = 0;
t_end   = 35;

%% ============================================================
% INITIAL STATE
% ============================================================

% Start exactly at the desired position.
% This avoids contaminating RMSE with a large initial step error.

x0_12 = zeros(12,1);

x0_12(1) = x_des;
x0_12(2) = y_des;
x0_12(3) = z_des;

%% ============================================================
% CASCADED PD + FEEDFORWARD GAINS
% ============================================================

Kp_x = 1.0;
Kd_x = 1.4;

Kp_y = 1.0;
Kd_y = 1.4;

Kp_z = 4.0;
Kd_z = 3.0;

Kp_phi = 0.8;
Kd_phi = 0.25;

Kp_theta = 0.8;
Kd_theta = 0.25;

Kp_psi = 0.5;
Kd_psi = 0.20;

%% ============================================================
% LQR MODEL
% ============================================================

A = zeros(12);

A(1,4) = 1;
A(2,5) = 1;
A(3,6) = 1;

A(4,8) = g;
A(5,7) = -g;

A(7,10) = 1;
A(8,11) = 1;
A(9,12) = 1;

B = zeros(12,4);

B(6,1) = 1/m_nominal;

B(10,2) = 1/Ix;
B(11,3) = 1/Iy;
B(12,4) = 1/Iz;

Q = diag([ ...
    20, ...
    20, ...
    30, ...
    5, ...
    5, ...
    8, ...
    40, ...
    40, ...
    10, ...
    2, ...
    2, ...
    2]);

R_lqr = diag([ ...
    1.0, ...
    0.5, ...
    0.5, ...
    0.5]);

K_lqr = lqr(A,B,Q,R_lqr);

%% ============================================================
% 3-AXIS LQI MODEL
% ============================================================

C_pos = zeros(3,12);

C_pos(1,1) = 1;
C_pos(2,2) = 1;
C_pos(3,3) = 1;

A_aug = zeros(15,15);

A_aug(1:12,1:12) = A;

% Integral definition:
%
% xi_dot = desired - actual
%
% With e = x - x_ref:
%
% xi_dot = -C_pos * e

A_aug(13:15,1:12) = -C_pos;

B_aug = zeros(15,4);

B_aug(1:12,:) = B;

q_aug_weights = [ ...
    20, ...
    20, ...
    30, ...
    5, ...
    5, ...
    8, ...
    40, ...
    40, ...
    10, ...
    2, ...
    2, ...
    2, ...
    20, ...
    20, ...
    25];

Q_aug = diag(q_aug_weights);

K_aug = lqr( ...
    A_aug, ...
    B_aug, ...
    Q_aug, ...
    R_lqr);

Kx_lqi = K_aug(:,1:12);

Ki_lqi = K_aug(:,13:15);

%% ============================================================
% CONTROLLABILITY
% ============================================================

rank_lqr = rank(ctrb(A,B));

rank_lqi = rank(ctrb(A_aug,B_aug));

fprintf('============================================\n');
fprintf('PD vs LQR vs LQI Robustness Comparison\n');
fprintf('============================================\n');

fprintf('LQR controllability rank: %d / 12\n', ...
    rank_lqr);

fprintf('LQI controllability rank: %d / 15\n', ...
    rank_lqi);

%% ============================================================
% RUN PD SIMULATION
% ============================================================

ode_pd = @(t,x) dynamics_pd( ...
    t, ...
    x, ...
    x_des, ...
    y_des, ...
    z_des, ...
    Kp_x, ...
    Kd_x, ...
    Kp_y, ...
    Kd_y, ...
    Kp_z, ...
    Kd_z, ...
    Kp_phi, ...
    Kd_phi, ...
    Kp_theta, ...
    Kd_theta, ...
    Kp_psi, ...
    Kd_psi, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    wind_start, ...
    F_wind, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

options = odeset( ...
    'RelTol',1e-7, ...
    'AbsTol',1e-9);

[t_pd,X_pd] = ode45( ...
    ode_pd, ...
    [t_start t_end], ...
    x0_12, ...
    options);

%% ============================================================
% RUN LQR SIMULATION
% ============================================================

ode_lqr = @(t,x) dynamics_lqr( ...
    t, ...
    x, ...
    K_lqr, ...
    x_des, ...
    y_des, ...
    z_des, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    wind_start, ...
    F_wind, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

[t_lqr,X_lqr] = ode45( ...
    ode_lqr, ...
    [t_start t_end], ...
    x0_12, ...
    options);

%% ============================================================
% RUN LQI SIMULATION
% ============================================================

x0_15 = zeros(15,1);

x0_15(1:12) = x0_12;

ode_lqi = @(t,x) dynamics_lqi( ...
    t, ...
    x, ...
    Kx_lqi, ...
    Ki_lqi, ...
    x_des, ...
    y_des, ...
    z_des, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    wind_start, ...
    F_wind, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

[t_lqi,X_lqi] = ode45( ...
    ode_lqi, ...
    [t_start t_end], ...
    x0_15, ...
    options);

%% ============================================================
% INTERPOLATE TO COMMON TIME VECTOR
% ============================================================

t_common = linspace( ...
    t_start, ...
    t_end, ...
    3501)';

Xpd = interp1( ...
    t_pd, ...
    X_pd, ...
    t_common, ...
    'linear');

Xlqr = interp1( ...
    t_lqr, ...
    X_lqr, ...
    t_common, ...
    'linear');

Xlqi = interp1( ...
    t_lqi, ...
    X_lqi, ...
    t_common, ...
    'linear');

%% ============================================================
% POSITION ERRORS
% ============================================================

ref_position = [ ...
    x_des, ...
    y_des, ...
    z_des];

err_pd_xyz = ...
    ref_position - Xpd(:,1:3);

err_lqr_xyz = ...
    ref_position - Xlqr(:,1:3);

err_lqi_xyz = ...
    ref_position - Xlqi(:,1:3);

err_pd = sqrt(sum(err_pd_xyz.^2,2));

err_lqr = sqrt(sum(err_lqr_xyz.^2,2));

err_lqi = sqrt(sum(err_lqi_xyz.^2,2));

%% ============================================================
% ANALYSIS WINDOWS
% ============================================================

idx_nominal = ...
    t_common < wind_start;

idx_wind = ...
    t_common >= wind_start & ...
    t_common < payload_time;

idx_combined = ...
    t_common >= payload_time;

%% ============================================================
% RMSE
% ============================================================

RMSE_pd_all = sqrt(mean(err_pd.^2));

RMSE_lqr_all = sqrt(mean(err_lqr.^2));

RMSE_lqi_all = sqrt(mean(err_lqi.^2));

RMSE_pd_wind = sqrt( ...
    mean(err_pd(idx_wind).^2));

RMSE_lqr_wind = sqrt( ...
    mean(err_lqr(idx_wind).^2));

RMSE_lqi_wind = sqrt( ...
    mean(err_lqi(idx_wind).^2));

RMSE_pd_combined = sqrt( ...
    mean(err_pd(idx_combined).^2));

RMSE_lqr_combined = sqrt( ...
    mean(err_lqr(idx_combined).^2));

RMSE_lqi_combined = sqrt( ...
    mean(err_lqi(idx_combined).^2));

%% ============================================================
% PEAK ERRORS AFTER WIND
% ============================================================

peak_pd_wind = max( ...
    err_pd(idx_wind));

peak_lqr_wind = max( ...
    err_lqr(idx_wind));

peak_lqi_wind = max( ...
    err_lqi(idx_wind));

%% ============================================================
% FINAL ERRORS
% ============================================================

final_pd_xyz = err_pd_xyz(end,:);

final_lqr_xyz = err_lqr_xyz(end,:);

final_lqi_xyz = err_lqi_xyz(end,:);

final_pd = err_pd(end);

final_lqr = err_lqr(end);

final_lqi = err_lqi(end);

%% ============================================================
% CONTROL HISTORY
% ============================================================

[ ...
    motors_pd, ...
    thrust_pd, ...
    sat_pd] = reconstruct_pd_controls( ...
    t_common, ...
    Xpd, ...
    x_des, ...
    y_des, ...
    z_des, ...
    Kp_x, ...
    Kd_x, ...
    Kp_y, ...
    Kd_y, ...
    Kp_z, ...
    Kd_z, ...
    Kp_phi, ...
    Kd_phi, ...
    Kp_theta, ...
    Kd_theta, ...
    Kp_psi, ...
    Kd_psi, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

[ ...
    motors_lqr, ...
    thrust_lqr, ...
    sat_lqr] = reconstruct_lqr_controls( ...
    t_common, ...
    Xlqr, ...
    K_lqr, ...
    x_des, ...
    y_des, ...
    z_des, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

[ ...
    motors_lqi, ...
    thrust_lqi, ...
    sat_lqi] = reconstruct_lqi_controls( ...
    t_common, ...
    Xlqi, ...
    Kx_lqi, ...
    Ki_lqi, ...
    x_des, ...
    y_des, ...
    z_des, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max);

%% Saturation time

sat_time_pd = trapz( ...
    t_common, ...
    double(sat_pd));

sat_time_lqr = trapz( ...
    t_common, ...
    double(sat_lqr));

sat_time_lqi = trapz( ...
    t_common, ...
    double(sat_lqi));

sat_pct_pd = ...
    100*sat_time_pd/t_end;

sat_pct_lqr = ...
    100*sat_time_lqr/t_end;

sat_pct_lqi = ...
    100*sat_time_lqi/t_end;

%% ============================================================
% PRINT RESULTS
% ============================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('OVERALL RMSE\n');
fprintf('============================================\n');

fprintf('PD  + FF: %.6f m\n', ...
    RMSE_pd_all);

fprintf('LQR + FF: %.6f m\n', ...
    RMSE_lqr_all);

fprintf('LQI + FF: %.6f m\n', ...
    RMSE_lqi_all);

fprintf('\n');

fprintf('============================================\n');
fprintf('CONSTANT WIND WINDOW: 10 - 20 s\n');
fprintf('============================================\n');

fprintf('PD  RMSE: %.6f m\n', ...
