fprintf('LQI RMSE: %.6f m\n', ...
    RMSE_lqi_combined);

fprintf('\n');

fprintf('============================================\n');
fprintf('FINAL POSITION ERRORS\n');
fprintf('============================================\n');

fprintf('PD:\n');

