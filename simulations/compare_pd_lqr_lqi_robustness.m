%% ============================================================
% LOCAL FUNCTION: PD DYNAMICS
% ============================================================

function dx = dynamics_pd( ...
    t, ...
    state, ...
    x_des, ...
    y_des, ...
    z_des, ...
    Kp_x, ...
    Kd_x, ...
    Kp_y, ...
    Kd_y, ...
    Kp_z, ...
    Kd_z, ...
    Kp_phi, ...
    Kd_phi, ...
    Kp_theta, ...
    Kd_theta, ...
    Kp_psi, ...
    Kd_psi, ...
    m_nominal, ...
    m_payload, ...
    payload_time, ...
    wind_start, ...
    F_wind, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max)

%% Extract state

x = state(1);
y = state(2);
z = state(3);

vx = state(4);
vy = state(5);
vz = state(6);

phi = state(7);
theta = state(8);
psi = state(9);

p = state(10);
q = state(11);
r = state(12);

%% Actual mass

if t < payload_time

    m_actual = m_nominal;

else

    m_actual = m_payload;

end

%% Position errors

ex = x_des - x;
ey = y_des - y;
ez = z_des - z;

%% Desired accelerations
% Static position target, therefore reference velocities and
% accelerations are zero.

ax_des = ...
    Kp_x*ex + ...
    Kd_x*(0-vx);

ay_des = ...
    Kp_y*ey + ...
    Kd_y*(0-vy);

%% Desired attitude

theta_des = ax_des/g;

phi_des = -ay_des/g;

psi_des = 0;

%% Altitude thrust

T_cmd = ...
    m_nominal*g + ...
    Kp_z*ez + ...
    Kd_z*(0-vz);

%% Attitude PD

tau_phi = ...
    Kp_phi*(phi_des-phi) + ...
    Kd_phi*(0-p);

tau_theta = ...
    Kp_theta*(theta_des-theta) + ...
    Kd_theta*(0-q);

tau_psi = ...
    Kp_psi*(psi_des-psi) + ...
    Kd_psi*(0-r);

u_cmd = [ ...
