% CONTROL RECONSTRUCTION: PD
% ============================================================

function [motor_log,T_log,sat_log] = ...
    reconstruct_pd_controls( ...
    t, ...
    X, ...
    x_des, ...
    y_des, ...
    z_des, ...
    Kp_x, ...
    Kd_x, ...
    Kp_y, ...
    Kd_y, ...
    Kp_z, ...
    Kd_z, ...
    Kp_phi, ...
    Kd_phi, ...
    Kp_theta, ...
    Kd_theta, ...
    Kp_psi, ...
    Kd_psi, ...
    m_nominal, ...
    g, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max)

N = length(t);

motor_log = zeros(N,4);

T_log = zeros(N,1);

sat_log = false(N,1);

M = [ ...
    1,      1,      1,      1;
    0,      L,      0,     -L;
   -L,      0,      L,      0;
    k_yaw, -k_yaw,  k_yaw, -k_yaw];

for k = 1:N

    state = X(k,:)';

    ex = x_des - state(1);
    ey = y_des - state(2);
    ez = z_des - state(3);

    ax_des = ...
        Kp_x*ex - ...
        Kd_x*state(4);

    ay_des = ...
        Kp_y*ey - ...
        Kd_y*state(5);

    theta_des = ax_des/g;

    phi_des = -ay_des/g;

    T_cmd = ...
        m_nominal*g + ...
        Kp_z*ez - ...
        Kd_z*state(6);

    tau_phi = ...
        Kp_phi*(phi_des-state(7)) - ...
        Kd_phi*state(10);

    tau_theta = ...
        Kp_theta*(theta_des-state(8)) - ...
        Kd_theta*state(11);

    tau_psi = ...
        Kp_psi*(0-state(9)) - ...
        Kd_psi*state(12);

    u_cmd = [ ...
        T_cmd;
        tau_phi;
        tau_theta;
        tau_psi];

    requested = M\u_cmd;

    sat_log(k) = any( ...
        requested < T_motor_min | ...
        requested > T_motor_max);

    motors = min( ...
        max(requested,T_motor_min), ...
        T_motor_max);

    u_actual = M*motors;

    motor_log(k,:) = motors';

    T_log(k) = u_actual(1);

end

end

