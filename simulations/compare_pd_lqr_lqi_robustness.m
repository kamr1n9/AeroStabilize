%% ============================================================
% LOCAL FUNCTION: NONLINEAR PLANT
% ============================================================

function dx = nonlinear_plant( ...
    t, ...
    state, ...
    u_cmd, ...
    m_actual, ...
    wind_start, ...
    F_wind, ...
    g, ...
    I, ...
    L, ...
    k_yaw, ...
    T_motor_min, ...
    T_motor_max)

vx = state(4);
vy = state(5);
vz = state(6);

phi = state(7);
theta = state(8);
psi = state(9);

p = state(10);
q = state(11);
r = state(12);

%% Mixer

M = [ ...
    1,      1,      1,      1;
    0,      L,      0,     -L;
   -L,      0,      L,      0;
    k_yaw, -k_yaw,  k_yaw, -k_yaw];

motor_thrust = M\u_cmd;

motor_thrust = min( ...
    max(motor_thrust,T_motor_min), ...
    T_motor_max);

u_actual = M*motor_thrust;

T = u_actual(1);

tau = u_actual(2:4);

%% Rotation

Rx = [ ...
    1,0,0;
    0,cos(phi),-sin(phi);
    0,sin(phi),cos(phi)];

Ry = [ ...
    cos(theta),0,sin(theta);
    0,1,0;
    -sin(theta),0,cos(theta)];

Rz = [ ...
    cos(psi),-sin(psi),0;
    sin(psi),cos(psi),0;
    0,0,1];

Rbw = Rz*Ry*Rx;

%% Forces

F_thrust = ...
    Rbw*[0;0;T];

F_gravity = ...
    [0;0;-m_actual*g];

if t >= wind_start

    F_external = F_wind;

else

    F_external = [0;0;0];

end

acc = ...
    (F_thrust + ...
     F_gravity + ...
     F_external) / m_actual;

%% Rotational dynamics

omega_body = [p;q;r];

omega_dot = I \ ( ...
    tau - ...
    cross(omega_body,I*omega_body));

%% Euler kinematics

E = [ ...
    1, ...
    sin(phi)*tan(theta), ...
    cos(phi)*tan(theta);
    0, ...
    cos(phi), ...
    -sin(phi);
    0, ...
    sin(phi)/cos(theta), ...
    cos(phi)/cos(theta)];

euler_dot = ...
    E*omega_body;

%% State derivative

dx = zeros(12,1);

dx(1) = vx;
dx(2) = vy;
dx(3) = vz;

dx(4:6) = acc;

dx(7:9) = euler_dot;

dx(10:12) = omega_dot;

end

