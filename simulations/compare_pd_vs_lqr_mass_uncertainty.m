%% ============================================================
%% PD CLOSED LOOP
%% ============================================================

function [ ...
    xdot, ...
    x_ref, ...
    motor_thrusts_sat, ...
    motor_thrusts_raw] = ...
    pd_mass_uncertainty_closed_loop( ...
    t, x, ...
    psi_des, ...
    Kp_x, Kd_x, ...
    Kp_y, Kd_y, ...
    Kp_z, Kd_z, ...
    Kp_phi, Kd_phi, ...
    Kp_theta, Kd_theta, ...
    Kp_psi, Kd_psi, ...
    m_nominal, ...
    m_actual, ...
    g, I, L, k_yaw, ...
    motor_thrust_min, ...
    motor_thrust_max)

%% Desired trajectory

[x_des, y_des, z_des, ...
 vx_des, vy_des, vz_des, ...
 ax_ff, ay_ff, az_ff] = ...
    helix_trajectory(t);

%% Reference state

x_ref = zeros(12,1);

x_ref(1) = x_des;
x_ref(2) = y_des;
x_ref(3) = z_des;

x_ref(4) = vx_des;
x_ref(5) = vy_des;
x_ref(6) = vz_des;

%% States

x_pos = x(1);
y_pos = x(2);
z_pos = x(3);

vx = x(4);
vy = x(5);
vz = x(6);

phi = x(7);
theta = x(8);
psi = x(9);

p = x(10);
q = x(11);
r = x(12);

%% Position error

e_x = ...
    x_des - x_pos;

e_y = ...
    y_des - y_pos;

e_z = ...
    z_des - z_pos;

e_vx = ...
    vx_des - vx;

e_vy = ...
    vy_des - vy;

e_vz = ...
    vz_des - vz;

%% ============================================================
%% OUTER LOOP + FEEDFORWARD
%% ============================================================

ax_des = ...
    ax_ff + ...
    Kp_x*e_x + ...
    Kd_x*e_vx;

ay_des = ...
    ay_ff + ...
    Kp_y*e_y + ...
    Kd_y*e_vy;

theta_des = ...
    ax_des / g;

phi_des = ...
    -ay_des / g;

max_angle = ...
    deg2rad(20);

theta_des = max( ...
    min(theta_des,max_angle), ...
    -max_angle);

phi_des = max( ...
    min(phi_des,max_angle), ...
    -max_angle);

%% ============================================================
%% ALTITUDE CONTROL
%%
%% IMPORTANT:
%% Controller uses NOMINAL mass, not actual mass.
%% ============================================================

T = ...
    m_nominal*g + ...
    m_nominal*az_ff + ...
    Kp_z*e_z + ...
    Kd_z*e_vz;

%% ============================================================
%% ATTITUDE PD
%% ============================================================

tau_phi = ...
    Kp_phi*(phi_des-phi) - ...
    Kd_phi*p;

tau_theta = ...
    Kp_theta*(theta_des-theta) - ...
    Kd_theta*q;

tau_psi = ...
    Kp_psi*(psi_des-psi) - ...
    Kd_psi*r;

%% ============================================================
%% MOTOR ALLOCATION
%% ============================================================

motor_thrusts_raw = ...
    motor_mixer( ...
        T, ...
        tau_phi, ...
        tau_theta, ...
        tau_psi, ...
        L, ...
        k_yaw);

motor_thrusts_sat = ...
    max( ...
        min( ...
            motor_thrusts_raw, ...
            motor_thrust_max), ...
        motor_thrust_min);

u_actual = ...
    motor_unmixer( ...
        motor_thrusts_sat, ...
        L, ...
        k_yaw);

%% ============================================================
%% ACTUAL PLANT
%%
%% Uses m_actual = 1.8 kg
%% ============================================================

xdot = ...
    quad_dynamics( ...
        x, ...
        u_actual, ...
        m_actual, ...
        g, ...
        I);

end

%% ============================================================
%% LQR CLOSED LOOP
%% ============================================================

function [ ...
    xdot, ...
    x_ref, ...
    motor_thrusts_sat, ...
    motor_thrusts_raw] = ...
    lqr_mass_uncertainty_closed_loop( ...
    t, x, ...
    K, ...
    m_nominal, ...
    m_actual, ...
    g, I, L, k_yaw, ...
    motor_thrust_min, ...
    motor_thrust_max)

%% Desired trajectory

[x_des, y_des, z_des, ...
 vx_des, vy_des,vz_des, ...
 ax_ff, ay_ff, az_ff] = ...
    helix_trajectory(t);

%% ============================================================
%% FEEDFORWARD ATTITUDE
%% ============================================================

theta_ff = ...
    ax_ff / g;

phi_ff = ...
    -ay_ff / g;

max_ff_angle = ...
    deg2rad(15);

theta_ff = max( ...
    min(theta_ff,max_ff_angle), ...
    -max_ff_angle);

phi_ff = max( ...
    min(phi_ff,max_ff_angle), ...
    -max_ff_angle);

%% ============================================================
%% REFERENCE STATE
%% ============================================================

x_ref = zeros(12,1);

x_ref(1) = x_des;
x_ref(2) = y_des;
x_ref(3) = z_des;

x_ref(4) = vx_des;
x_ref(5) = vy_des;
x_ref(6) = vz_des;

x_ref(7) = phi_ff;
x_ref(8) = theta_ff;

%% ============================================================
%% LQR FEEDBACK
%% ============================================================

e = ...
    x - x_ref;

delta_u = ...
    -K * e;

delta_T = ...
    delta_u(1);

tau_phi = ...
    delta_u(2);

tau_theta = ...
    delta_u(3);

tau_psi = ...
    delta_u(4);

%% ============================================================
%% NOMINAL FEEDFORWARD THRUST
%%
%% LQR also does NOT know actual mass.
%% ============================================================

T_ff = ...
    m_nominal * ...
    (g + az_ff);

T = ...
    T_ff + delta_T;

%% ============================================================
%% MOTOR ALLOCATION
%% ============================================================

motor_thrusts_raw = ...
    motor_mixer( ...
        T, ...
        tau_phi, ...
        tau_theta, ...
        tau_psi, ...
        L, ...
        k_yaw);

motor_thrusts_sat = ...
