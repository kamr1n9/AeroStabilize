%% AeroStabilize - PD vs LQR under Mass Uncertainty
%
% Robustness comparison:
% Cascaded PD + Feedforward
% vs.
% LQR + Feedforward
%
% Controller model:
% Nominal mass = 1.5 kg
%
% Actual nonlinear plant:
% +20 % mass uncertainty = 1.8 kg
%
% Both controllers use the NOMINAL model.
% Neither controller knows the actual increased mass.

clear;
clc;
close all;

addpath('../models');
addpath('../trajectories');

run('../parameters/quadcopter_params.m');

%% ============================================================
%% NOMINAL AND ACTUAL MASS
%% ============================================================

m_nominal = m;

mass_increase = 0.20;

m_actual = ...
    m_nominal * (1 + mass_increase);

fprintf('Nominal mass: %.3f kg\n', m_nominal);
fprintf('Actual mass:  %.3f kg\n', m_actual);
fprintf('Mass error:   +%.1f %%\n', mass_increase*100);

%% ============================================================
%% COMMON SETTINGS
%% ============================================================

tspan = [0 20];

motor_thrust_min = 0.0;
motor_thrust_max = 7.5;

%% ============================================================
%% INITIAL STATE
%% ============================================================

x0 = zeros(12,1);

[x_start, y_start, z_start, ...
 vx_start, vy_start, vz_start] = ...
    helix_trajectory(0);

x0(1) = x_start;
x0(2) = y_start;
x0(3) = z_start;

x0(4) = vx_start;
x0(5) = vy_start;
x0(6) = vz_start;

%% ============================================================
%% PD CONTROLLER GAINS
%% ============================================================

psi_des = 0;

Kp_x = 1.0;
Kd_x = 1.4;

Kp_y = 1.0;
Kd_y = 1.4;

Kp_z = 4.0;
Kd_z = 3.0;

Kp_phi = 0.8;
Kd_phi = 0.25;

Kp_theta = 0.8;
Kd_theta = 0.25;

Kp_psi = 0.5;
Kd_psi = 0.20;

%% ============================================================
%% LQR DESIGN USING NOMINAL MODEL
%% ============================================================

A = zeros(12,12);

A(1,4) = 1;
A(2,5) = 1;
A(3,6) = 1;

A(4,8) = g;
A(5,7) = -g;

A(7,10) = 1;
A(8,11) = 1;
A(9,12) = 1;

B = zeros(12,4);

B(6,1) = ...
    1 / m_nominal;

B(10,2) = ...
    1 / I(1,1);

B(11,3) = ...
    1 / I(2,2);

B(12,4) = ...
    1 / I(3,3);

Co = ctrb(A,B);

fprintf( ...
    'LQR controllability rank: %d / 12\n', ...
    rank(Co));

%% LQR weighting

Q = diag([ ...
    20, ...
    20, ...
    30, ...
    5, ...
    5, ...
    8, ...
    40, ...
    40, ...
    10, ...
    2, ...
    2, ...
    2]);

R = diag([ ...
    1.0, ...
    0.5, ...
    0.5, ...
    0.5]);

K = lqr(A,B,Q,R);

%% ============================================================
%% RUN PD SIMULATION
%% ============================================================

pd_dynamics = @(t,x) ...
    pd_mass_uncertainty_closed_loop( ...
        t, x, ...
        psi_des, ...
        Kp_x, Kd_x, ...
        Kp_y, Kd_y, ...
        Kp_z, Kd_z, ...
        Kp_phi, Kd_phi, ...
        Kp_theta, Kd_theta, ...
        Kp_psi, Kd_psi, ...
        m_nominal, ...
        m_actual, ...
        g, I, L, k_yaw, ...
        motor_thrust_min, ...
        motor_thrust_max);

[t_pd, x_pd] = ...
    ode45( ...
        pd_dynamics, ...
        tspan, ...
        x0);

%% ============================================================
%% RUN LQR SIMULATION
%% ============================================================

lqr_dynamics = @(t,x) ...
    lqr_mass_uncertainty_closed_loop( ...
        t, x, ...
        K, ...
        m_nominal, ...
        m_actual, ...
        g, I, L, k_yaw, ...
        motor_thrust_min, ...
        motor_thrust_max);

[t_lqr, x_lqr] = ...
    ode45( ...
        lqr_dynamics, ...
        tspan, ...
        x0);

%% ============================================================
%% LOG PD DATA
%% ============================================================

N_pd = length(t_pd);

pd_ref = zeros(N_pd,12);

pd_motor = zeros(N_pd,4);
pd_motor_raw = zeros(N_pd,4);

for k = 1:N_pd

    [~, ...
     ref_k, ...
     motor_k, ...
     motor_raw_k] = ...
        pd_mass_uncertainty_closed_loop( ...
            t_pd(k), ...
            x_pd(k,:)', ...
            psi_des, ...
            Kp_x, Kd_x, ...
            Kp_y, Kd_y, ...
            Kp_z, Kd_z, ...
            Kp_phi, Kd_phi, ...
            Kp_theta, Kd_theta, ...
            Kp_psi, Kd_psi, ...
            m_nominal, ...
            m_actual, ...
            g, I, L, k_yaw, ...
            motor_thrust_min, ...
            motor_thrust_max);

    pd_ref(k,:) = ref_k';

    pd_motor(k,:) = motor_k';
    pd_motor_raw(k,:) = motor_raw_k';

end

%% ============================================================
%% LOG LQR DATA
%% ============================================================

N_lqr = length(t_lqr);

lqr_ref = zeros(N_lqr,12);

lqr_motor = zeros(N_lqr,4);
lqr_motor_raw = zeros(N_lqr,4);

for k = 1:N_lqr

    [~, ...
     ref_k, ...
     motor_k, ...
     motor_raw_k] = ...
        lqr_mass_uncertainty_closed_loop( ...
            t_lqr(k), ...
            x_lqr(k,:)', ...
            K, ...
            m_nominal, ...
            m_actual, ...
            g, I, L, k_yaw, ...
            motor_thrust_min, ...
            motor_thrust_max);

    lqr_ref(k,:) = ref_k';

    lqr_motor(k,:) = motor_k';
    lqr_motor_raw(k,:) = motor_raw_k';

end

%% ============================================================
%% PD TRACKING ERRORS
%% ============================================================

pd_error_x = ...
    pd_ref(:,1) - x_pd(:,1);

pd_error_y = ...
    pd_ref(:,2) - x_pd(:,2);

pd_error_z = ...
    pd_ref(:,3) - x_pd(:,3);

pd_position_error = sqrt( ...
    pd_error_x.^2 + ...
    pd_error_y.^2 + ...
    pd_error_z.^2);

pd_RMSE = ...
    sqrt(mean(pd_position_error.^2));

pd_max_error = ...
    max(pd_position_error);

pd_final_error = ...
    pd_position_error(end);

pd_final_altitude_error = ...
    pd_error_z(end);

%% ============================================================
%% LQR TRACKING ERRORS
%% ============================================================

lqr_error_x = ...
    lqr_ref(:,1) - x_lqr(:,1);

lqr_error_y = ...
    lqr_ref(:,2) - x_lqr(:,2);

lqr_error_z = ...
    lqr_ref(:,3) - x_lqr(:,3);

lqr_position_error = sqrt( ...
    lqr_error_x.^2 + ...
    lqr_error_y.^2 + ...
    lqr_error_z.^2);

lqr_RMSE = ...
    sqrt(mean(lqr_position_error.^2));

lqr_max_error = ...
    max(lqr_position_error);

lqr_final_error = ...
    lqr_position_error(end);

lqr_final_altitude_error = ...
    lqr_error_z(end);

%% ============================================================
%% MAXIMUM ATTITUDE
%% ============================================================

pd_max_roll = ...
    max(abs(rad2deg(x_pd(:,7))));

pd_max_pitch = ...
    max(abs(rad2deg(x_pd(:,8))));

pd_max_yaw = ...
    max(abs(rad2deg(x_pd(:,9))));

lqr_max_roll = ...
    max(abs(rad2deg(x_lqr(:,7))));

lqr_max_pitch = ...
    max(abs(rad2deg(x_lqr(:,8))));

lqr_max_yaw = ...
    max(abs(rad2deg(x_lqr(:,9))));

%% ============================================================
%% MOTOR STATISTICS
%% ============================================================

pd_max_motor = ...
    max(pd_motor, [], 'all');

pd_min_motor = ...
    min(pd_motor, [], 'all');

lqr_max_motor = ...
    max(lqr_motor, [], 'all');

lqr_min_motor = ...
    min(lqr_motor, [], 'all');

%% ============================================================
%% SATURATION ANALYSIS
%% ============================================================

pd_sat_log = any( ...
    pd_motor_raw > motor_thrust_max | ...
    pd_motor_raw < motor_thrust_min, ...
    2);

pd_sat_duration = ...
    trapz( ...
        t_pd, ...
        double(pd_sat_log));

pd_sat_percentage = ...
    100 * pd_sat_duration / ...
    (t_pd(end)-t_pd(1));

lqr_sat_log = any( ...
    lqr_motor_raw > motor_thrust_max | ...
    lqr_motor_raw < motor_thrust_min, ...
    2);

lqr_sat_duration = ...
    trapz( ...
        t_lqr, ...
        double(lqr_sat_log));

lqr_sat_percentage = ...
    100 * lqr_sat_duration / ...
    (t_lqr(end)-t_lqr(1));

